console.log(3 < 1); // this is less than operator. It will return false because 3 is not less than 1. It is used to compare two values and return a boolean value (true or false) based on the comparison.


console.log(3 > 1); // this is greater than operator. It will return true because 3 is greater than 1. It is used to compare two values and return a boolean value (true or false) based on the comparison.


console.log(3 >= 1); // this is greater than or equal to operator. It will return true because 3 is greater than 1. It is used to compare two values and return a boolean value (true or false) based on the comparison.


console.log(3 <= 1); // this is less than or equal to operator. It will return false because 3 is not less than or equal to 1. It is used to compare two values and return a boolean value (true or false) based on the comparison.


console.log(3 == 1); // this is equal to operator. It will return false because 3 is not equal to 1. It is used to compare two values and return a boolean value (true or false) based on the comparison.


console.log(3 != 1); // this is not equal to operator. It will return true because 3 is not equal to 1. It is used to compare two values and return a boolean value (true or false) based on the comparison.


console.log(3 === 1); // this is strict equal to operator. It will return false because 3 is not strictly equal to 1. It is used to compare two values and return a boolean value (true or false) based on the comparison.


console.log(3 !== 1); // this is strict not equal to operator. It will return true because 3 is not strictly equal to 1. It is used to compare two values and return a boolean value (true or false) based on the comparison.

// What is Comparison Operators? Comparison operators are used to compare two values and return a boolean value (true or false) based on the comparison. They are used in conditional statements to control the flow of a program based on certain conditions. The comparison operators in JavaScript are: equal to (==), not equal to (!=), strict equal to (===), strict not equal to (!==), greater than (>), less than (<), greater than or equal to (>=), and less than or equal to (<=).